-- Flyway V1: 初始化 schema (镜像 Python 的 10 个 Alembic 迁移)
-- 包含 25 张表:多租户、用户、知识图谱、学习者状态、事件、审计、RAG、题库、班级、隐私、任务、通知、Critic

-- ============== 多租户 ==============
CREATE TABLE tenants (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(128) NOT NULL,
    slug        VARCHAR(64)  NOT NULL UNIQUE,
    plan        VARCHAR(16)  NOT NULL DEFAULT 'free',
    is_active   BOOLEAN      NOT NULL DEFAULT TRUE,
    settings    JSONB        NOT NULL DEFAULT '{}'::jsonb,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX ix_tenants_plan ON tenants (plan);

CREATE TABLE tenant_quotas (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id                   BIGINT NOT NULL UNIQUE REFERENCES tenants(id),
    max_users                   INTEGER NOT NULL DEFAULT 100,
    max_llm_tokens_per_month    INTEGER NOT NULL DEFAULT 100000,
    current_llm_tokens          INTEGER NOT NULL DEFAULT 0,
    period_start                TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_at                  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at                  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_tenant_quotas_tenant_id ON tenant_quotas (tenant_id);

-- ============== 学习者与用户 ==============
CREATE TABLE learners (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id   BIGINT NOT NULL DEFAULT 1 REFERENCES tenants(id),
    public_id   VARCHAR(64) NOT NULL UNIQUE,
    name        VARCHAR(128) NOT NULL DEFAULT '',
    profile     JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_learners_tenant_id ON learners (tenant_id);
CREATE INDEX ix_learners_public_id ON learners (public_id);

CREATE TABLE users (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email               VARCHAR(255) NOT NULL UNIQUE,
    password_hash       VARCHAR(255) NOT NULL,
    role                VARCHAR(16)  NOT NULL DEFAULT 'student',
    is_active           BOOLEAN NOT NULL DEFAULT TRUE,
    is_verified         BOOLEAN NOT NULL DEFAULT FALSE,
    tenant_id           BIGINT NOT NULL DEFAULT 1 REFERENCES tenants(id),
    learner_id          BIGINT REFERENCES learners(id) ON DELETE SET NULL,
    last_login_at       TIMESTAMPTZ,
    failed_login_count  INTEGER NOT NULL DEFAULT 0,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_users_email        ON users (email);
CREATE INDEX ix_users_tenant_id    ON users (tenant_id);
CREATE INDEX ix_users_learner_id   ON users (learner_id);
CREATE INDEX ix_users_role         ON users (role);

CREATE TABLE refresh_tokens (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    token_hash  VARCHAR(128) NOT NULL UNIQUE,
    expires_at  TIMESTAMPTZ NOT NULL,
    revoked     BOOLEAN NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_refresh_tokens_user_id    ON refresh_tokens (user_id);
CREATE INDEX ix_refresh_tokens_expires_at ON refresh_tokens (expires_at);

-- ============== 知识图谱 ==============
CREATE TABLE knowledge_nodes (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id   VARCHAR(64) NOT NULL UNIQUE,
    name        VARCHAR(128) NOT NULL,
    subject     VARCHAR(32)  NOT NULL DEFAULT 'math',
    difficulty  DOUBLE PRECISION NOT NULL DEFAULT 0.5,
    description TEXT NOT NULL DEFAULT '',
    tags        JSONB NOT NULL DEFAULT '[]'::jsonb,
    version     INTEGER NOT NULL DEFAULT 1,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_knowledge_nodes_public_id ON knowledge_nodes (public_id);

CREATE TABLE knowledge_prerequisites (
    node_id         BIGINT NOT NULL REFERENCES knowledge_nodes(id) ON DELETE CASCADE,
    prerequisite_id BIGINT NOT NULL REFERENCES knowledge_nodes(id) ON DELETE CASCADE,
    PRIMARY KEY (node_id, prerequisite_id)
);
CREATE INDEX ix_kp_node_id         ON knowledge_prerequisites (node_id);
CREATE INDEX ix_kp_prerequisite_id ON knowledge_prerequisites (prerequisite_id);

-- ============== 学习者状态与练习 ==============
CREATE TABLE knowledge_states (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id     BIGINT NOT NULL DEFAULT 1 REFERENCES tenants(id),
    learner_id    BIGINT NOT NULL REFERENCES learners(id) ON DELETE CASCADE,
    knowledge_id  VARCHAR(64) NOT NULL,
    mastery       DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    alpha         DOUBLE PRECISION NOT NULL DEFAULT 0.1,
    beta          DOUBLE PRECISION NOT NULL DEFAULT 0.2,
    attempts      INTEGER NOT NULL DEFAULT 0,
    correct_count INTEGER NOT NULL DEFAULT 0,
    streak        INTEGER NOT NULL DEFAULT 0,
    last_attempt  TIMESTAMPTZ,
    version       INTEGER NOT NULL DEFAULT 1,
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_state_learner_knowledge UNIQUE (learner_id, knowledge_id)
);
CREATE INDEX ix_state_tenant_id ON knowledge_states (tenant_id);
CREATE INDEX ix_state_learner_id ON knowledge_states (learner_id);

CREATE TABLE submissions (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id           BIGINT NOT NULL DEFAULT 1 REFERENCES tenants(id),
    learner_id          BIGINT NOT NULL REFERENCES learners(id) ON DELETE CASCADE,
    knowledge_id        VARCHAR(64) NOT NULL,
    is_correct          BOOLEAN NOT NULL,
    time_spent_seconds  DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_submissions_learner_knowledge ON submissions (learner_id, knowledge_id);
CREATE INDEX ix_submissions_created_at        ON submissions (created_at);
CREATE INDEX ix_submissions_tenant_id         ON submissions (tenant_id);

CREATE TABLE review_schedules (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id        BIGINT NOT NULL DEFAULT 1 REFERENCES tenants(id),
    learner_id       BIGINT NOT NULL REFERENCES learners(id) ON DELETE CASCADE,
    knowledge_id     VARCHAR(64) NOT NULL,
    easiness_factor  DOUBLE PRECISION NOT NULL DEFAULT 2.5,
    interval_days    DOUBLE PRECISION NOT NULL DEFAULT 1.0,
    repetition       INTEGER NOT NULL DEFAULT 0,
    total_reviews    INTEGER NOT NULL DEFAULT 0,
    next_review      TIMESTAMPTZ NOT NULL,
    last_review      TIMESTAMPTZ,
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_review_learner_knowledge UNIQUE (learner_id, knowledge_id)
);
CREATE INDEX ix_review_learner_id  ON review_schedules (learner_id);
CREATE INDEX ix_review_next_review ON review_schedules (next_review);
CREATE INDEX ix_review_tenant_id   ON review_schedules (tenant_id);

-- ============== 事件溯源 ==============
CREATE TABLE events (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id         BIGINT NOT NULL DEFAULT 1 REFERENCES tenants(id),
    public_id         VARCHAR(64) NOT NULL UNIQUE,
    type              VARCHAR(64) NOT NULL,
    source            VARCHAR(64) NOT NULL,
    learner_public_id VARCHAR(64) NOT NULL,
    data              JSONB NOT NULL DEFAULT '{}'::jsonb,
    correlation_id    VARCHAR(64),
    timestamp         TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_events_public_id         ON events (public_id);
CREATE INDEX ix_events_type              ON events (type);
CREATE INDEX ix_events_learner_public_id ON events (learner_public_id);
CREATE INDEX ix_events_correlation_id    ON events (correlation_id);
CREATE INDEX ix_events_learner_type      ON events (learner_public_id, type);
CREATE INDEX ix_events_timestamp         ON events (timestamp);
CREATE INDEX ix_events_tenant_id         ON events (tenant_id);

-- ============== 审计日志(HMAC 链) ==============
CREATE TABLE audit_logs (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id   BIGINT NOT NULL DEFAULT 1 REFERENCES tenants(id),
    actor       VARCHAR(128) NOT NULL,
    action      VARCHAR(64)  NOT NULL,
    target      VARCHAR(256) NOT NULL,
    ip          VARCHAR(64)  NOT NULL DEFAULT '',
    user_agent  VARCHAR(256) NOT NULL DEFAULT '',
    metadata    JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    prev_hash   VARCHAR(128) NOT NULL DEFAULT '',
    curr_hash   VARCHAR(128) NOT NULL DEFAULT ''
);
CREATE INDEX ix_audit_created_at ON audit_logs (created_at);
CREATE INDEX ix_audit_tenant_id  ON audit_logs (tenant_id);
CREATE INDEX ix_audit_curr_hash  ON audit_logs (curr_hash);
CREATE INDEX ix_audit_action     ON audit_logs (action);

-- ============== RAG 知识库 ==============
CREATE TABLE documents (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id     BIGINT NOT NULL DEFAULT 1 REFERENCES tenants(id),
    title         VARCHAR(256) NOT NULL,
    source_type   VARCHAR(32)  NOT NULL DEFAULT 'text',
    source_url    VARCHAR(512),
    content_hash  VARCHAR(64)  NOT NULL UNIQUE,
    status        VARCHAR(16)  NOT NULL DEFAULT 'pending',
    error_message VARCHAR(512),
    total_chunks  INTEGER NOT NULL DEFAULT 0,
    metadata      JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_documents_title        ON documents (title);
CREATE INDEX ix_documents_status       ON documents (status);
CREATE INDEX ix_documents_content_hash ON documents (content_hash);
CREATE INDEX ix_documents_tenant_id    ON documents (tenant_id);

CREATE TABLE document_chunks (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id    BIGINT NOT NULL DEFAULT 1 REFERENCES tenants(id),
    document_id  BIGINT NOT NULL REFERENCES documents(id) ON DELETE CASCADE,
    chunk_index  INTEGER NOT NULL,
    content      TEXT NOT NULL,
    embedding    JSONB NOT NULL,
    token_count  INTEGER NOT NULL DEFAULT 0,
    metadata     JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_chunk_doc_index UNIQUE (document_id, chunk_index)
);
CREATE INDEX ix_chunks_document_id ON document_chunks (document_id);
CREATE INDEX ix_chunks_tenant_id   ON document_chunks (tenant_id);

-- ============== 题库 ==============
CREATE TABLE questions (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id         BIGINT NOT NULL DEFAULT 1 REFERENCES tenants(id),
    knowledge_id      VARCHAR(64) NOT NULL,
    question_type     VARCHAR(32) NOT NULL,
    difficulty        INTEGER NOT NULL DEFAULT 3,
    content           JSONB NOT NULL,
    answer            TEXT NOT NULL,
    analysis          TEXT,
    status            VARCHAR(16) NOT NULL DEFAULT 'draft',
    content_embedding JSONB,
    created_by        INTEGER,
    metadata          JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_questions_knowledge_id ON questions (knowledge_id);
CREATE INDEX ix_questions_status       ON questions (status);
CREATE INDEX ix_questions_tenant_id    ON questions (tenant_id);

-- ============== 班级与作业 ==============
CREATE TABLE classes (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id   BIGINT NOT NULL DEFAULT 1 REFERENCES tenants(id),
    name        VARCHAR(128) NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    teacher_id  BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    invite_code VARCHAR(16) NOT NULL UNIQUE,
    is_active   BOOLEAN NOT NULL DEFAULT TRUE,
    metadata    JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_classes_teacher_id  ON classes (teacher_id);
CREATE INDEX ix_classes_invite_code ON classes (invite_code);
CREATE INDEX ix_classes_tenant_id   ON classes (tenant_id);

CREATE TABLE class_members (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id  BIGINT NOT NULL DEFAULT 1 REFERENCES tenants(id),
    class_id   BIGINT NOT NULL REFERENCES classes(id) ON DELETE CASCADE,
    learner_id BIGINT NOT NULL REFERENCES learners(id) ON DELETE CASCADE,
    joined_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_class_member UNIQUE (class_id, learner_id)
);
CREATE INDEX ix_class_members_class_id   ON class_members (class_id);
CREATE INDEX ix_class_members_learner_id ON class_members (learner_id);
CREATE INDEX ix_class_members_tenant_id  ON class_members (tenant_id);

CREATE TABLE assignments (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id    BIGINT NOT NULL DEFAULT 1 REFERENCES tenants(id),
    title        VARCHAR(256) NOT NULL,
    description  TEXT NOT NULL DEFAULT '',
    class_id     BIGINT NOT NULL REFERENCES classes(id) ON DELETE CASCADE,
    teacher_id   BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    question_ids JSONB NOT NULL DEFAULT '[]'::jsonb,
    status       VARCHAR(16) NOT NULL DEFAULT 'draft',
    due_at       TIMESTAMPTZ,
    metadata     JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_assignments_class_id   ON assignments (class_id);
CREATE INDEX ix_assignments_teacher_id ON assignments (teacher_id);
CREATE INDEX ix_assignments_status     ON assignments (status);
CREATE INDEX ix_assignments_tenant_id  ON assignments (tenant_id);

-- ============== 隐私合规 ==============
CREATE TABLE privacy_consents (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id       BIGINT NOT NULL DEFAULT 1 REFERENCES tenants(id),
    user_id         BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    consent_type    VARCHAR(32) NOT NULL,
    granted         BOOLEAN NOT NULL,
    consent_version VARCHAR(16) NOT NULL DEFAULT '1.0',
    ip              VARCHAR(64) NOT NULL DEFAULT '',
    user_agent      VARCHAR(256) NOT NULL DEFAULT '',
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_consent_user_id      ON privacy_consents (user_id);
CREATE INDEX ix_consent_consent_type ON privacy_consents (consent_type);
CREATE INDEX ix_consent_user_type    ON privacy_consents (user_id, consent_type);
CREATE INDEX ix_consent_tenant_id    ON privacy_consents (tenant_id);

CREATE TABLE privacy_deletion_requests (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id    BIGINT NOT NULL DEFAULT 1 REFERENCES tenants(id),
    user_id      BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    status       VARCHAR(16) NOT NULL DEFAULT 'pending',
    requested_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    scheduled_at TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,
    cancelled_at TIMESTAMPTZ,
    reason       TEXT NOT NULL DEFAULT '',
    metadata     JSONB NOT NULL DEFAULT '{}'::jsonb
);
CREATE INDEX ix_pdr_user_id   ON privacy_deletion_requests (user_id);
CREATE INDEX ix_pdr_status    ON privacy_deletion_requests (status);
CREATE INDEX ix_pdr_tenant_id ON privacy_deletion_requests (tenant_id);

CREATE TABLE data_export_jobs (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id       BIGINT NOT NULL DEFAULT 1 REFERENCES tenants(id),
    user_id         BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    status          VARCHAR(16) NOT NULL DEFAULT 'pending',
    requested_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    completed_at    TIMESTAMPTZ,
    download_url    VARCHAR(512),
    file_size_bytes INTEGER NOT NULL DEFAULT 0,
    error_message   VARCHAR(512),
    metadata        JSONB NOT NULL DEFAULT '{}'::jsonb
);
CREATE INDEX ix_dej_user_id   ON data_export_jobs (user_id);
CREATE INDEX ix_dej_status    ON data_export_jobs (status);
CREATE INDEX ix_dej_tenant_id ON data_export_jobs (tenant_id);

-- ============== 任务执行 ==============
CREATE TABLE task_executions (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id     BIGINT NOT NULL DEFAULT 1 REFERENCES tenants(id),
    task_name     VARCHAR(64) NOT NULL,
    status        VARCHAR(16) NOT NULL,
    started_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    completed_at  TIMESTAMPTZ,
    duration_ms   INTEGER NOT NULL DEFAULT 0,
    error_message TEXT,
    metadata      JSONB NOT NULL DEFAULT '{}'::jsonb,
    triggered_by  VARCHAR(64) NOT NULL DEFAULT 'scheduler'
);
CREATE INDEX ix_task_task_name  ON task_executions (task_name);
CREATE INDEX ix_task_status     ON task_executions (status);
CREATE INDEX ix_task_started_at ON task_executions (started_at);
CREATE INDEX ix_task_tenant_id  ON task_executions (tenant_id);

-- ============== 通知系统 ==============
CREATE TABLE notifications (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id    BIGINT NOT NULL DEFAULT 1 REFERENCES tenants(id),
    user_id      BIGINT NOT NULL REFERENCES users(id),
    type         VARCHAR(32) NOT NULL,
    channel      VARCHAR(16) NOT NULL,
    status       VARCHAR(16) NOT NULL DEFAULT 'pending',
    priority     INTEGER NOT NULL DEFAULT 0,
    title        VARCHAR(128) NOT NULL,
    body         TEXT NOT NULL,
    payload      JSONB NOT NULL DEFAULT '{}'::jsonb,
    error_message TEXT,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    sent_at      TIMESTAMPTZ,
    delivered_at TIMESTAMPTZ,
    read_at      TIMESTAMPTZ
);
CREATE INDEX ix_notif_user_id    ON notifications (user_id);
CREATE INDEX ix_notif_type       ON notifications (type);
CREATE INDEX ix_notif_status     ON notifications (status);
CREATE INDEX ix_notif_created_at ON notifications (created_at);
CREATE INDEX ix_notif_tenant_id  ON notifications (tenant_id);

CREATE TABLE notification_preferences (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id          BIGINT NOT NULL DEFAULT 1 REFERENCES tenants(id),
    user_id            BIGINT NOT NULL UNIQUE REFERENCES users(id),
    ws_enabled         BOOLEAN NOT NULL DEFAULT TRUE,
    email_enabled      BOOLEAN NOT NULL DEFAULT FALSE,
    push_enabled       BOOLEAN NOT NULL DEFAULT FALSE,
    quiet_hours_start  SMALLINT,
    quiet_hours_end    SMALLINT,
    min_priority       INTEGER NOT NULL DEFAULT 0,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_notif_pref_tenant_id ON notification_preferences (tenant_id);

-- ============== Critic 评估 ==============
CREATE TABLE critiques (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    learner_id           VARCHAR(64) NOT NULL,
    knowledge_id         VARCHAR(128) NOT NULL,
    teaching_event_id    VARCHAR(64),
    overall              SMALLINT NOT NULL,
    scores               JSONB NOT NULL DEFAULT '{}'::jsonb,
    critique             TEXT NOT NULL,
    needs_regeneration   BOOLEAN NOT NULL DEFAULT FALSE,
    regenerated          BOOLEAN NOT NULL DEFAULT FALSE,
    original_response    TEXT NOT NULL,
    regenerated_response TEXT,
    critic_model         VARCHAR(64),
    critic_tokens        INTEGER NOT NULL DEFAULT 0,
    tenant_id            BIGINT NOT NULL DEFAULT 1 REFERENCES tenants(id),
    created_at           TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_critiques_learner_id        ON critiques (learner_id);
CREATE INDEX ix_critiques_knowledge_id      ON critiques (knowledge_id);
CREATE INDEX ix_critiques_teaching_event_id ON critiques (teaching_event_id);
CREATE INDEX ix_critiques_tenant_id         ON critiques (tenant_id);
CREATE INDEX ix_critiques_created_at        ON critiques (created_at);
